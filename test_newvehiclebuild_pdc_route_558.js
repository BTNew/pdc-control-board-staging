  assert.match(check, /cc_addresses":\[\]\}'::pg_catalog\.jsonb, '1IRU519 J138000880 EPT'\) IS FALSE/);
  assert.match(check, /gmail_receiving_provider/);
  assert.match(check, /workshopupdates@pmgwa\.com\.au/);
  assert.match(check, /sales@pmgwa\.com\.au/);
  assert.match(check, /newvehiclebuild@pmgwa\.com\.au\.example\.net/);
  assert.match(check, /Microsoft_receiving_provider/);
  assert.match(check, /FW: 1IRU519 J138000880 EPT'\) IS TRUE/);
  assert.match(check, /forwarded":"true"/);
  assert.match(check, /RE: New vehicle order for 13102818 - PMG Build'\) IS FALSE/);
  assert.match(check, /pdc@pmgwa\.com\.au\.example\.net/);
  assert.match(up, /pin count is not 241/);
  assert.doesNotMatch(check, /expected_function_md5/i);
  assert.doesNotMatch(check, /::(?:pg_catalog\.)?regprocedure/);
  assert.match(check, /AS ok/);
  assert.match(check, /AS detail/);
  assert.doesNotMatch(up, /CREATE OR REPLACE FUNCTION public\.pdc_import_job_parts_csv_20260912/);
  assert.doesNotMatch(up, /CREATE OR REPLACE FUNCTION public\.record_pdc_person_parts_complete_20260913/);
